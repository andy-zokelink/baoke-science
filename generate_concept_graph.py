def classify_domain(concept_name, definition=''):
    """基于关键词将概念归类到领域"""
    text = concept_name + ' ' + definition
    scores = {}
    for domain, keywords in DOMAIN_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in text)
        if score > 0:
            scores[domain] = score
    if not scores:
        return '综合'
    # 返回得分最高的领域
    return max(scores, key=scores.get)


def compute_wrong_counts():
    """从 student_answers 按概念名聚合错题数"""
    conn = get_conn()
    rows = conn.execute('''
        SELECT rq.knowledge_point, sa.is_correct, COUNT(*) as cnt
        FROM raw_questions rq
        JOIN student_answers sa ON rq.id = sa.question_id
        GROUP BY rq.knowledge_point, sa.is_correct
    ''').fetchall()
    conn.close()

    stats = defaultdict(lambda: {'wrong': 0, 'total': 0})
    for r in rows:
        kp = r['knowledge_point']
        cnt = r['cnt']
        stats[kp]['total'] += cnt
        if r['is_correct'] == '✗':
            stats[kp]['wrong'] += cnt
    return stats


def build_graph():
    """主函数：构建知识图谱数据"""
    conn = get_conn()
    concepts = conn.execute('''
        SELECT c.id, c.name, c.definition, ct.name as type_name
        FROM concepts c
        JOIN concept_types ct ON c.concept_type_id = ct.id
        ORDER BY c.id
    ''').fetchall()
    conn.close()

    wrong_stats = compute_wrong_counts()

    # 构建概念名 → id 映射
    name_to_id = {}
    for c in concepts:
        name = c['name'].strip()
        # 处理同名概念（如两个"物质的变化（物理变化与化学变化）"）
        if name in name_to_id:
            # 保留第一个，但记录同名
            continue
        name_to_id[name] = c['id']

    # 处理同名概念 - 创建别名映射
    name_to_ids = defaultdict(list)
    for c in concepts:
        name_to_ids[c['name'].strip()].append(c)

    # 构建 nodes
    nodes = []
    node_id_map = {}  # id -> node index
    for idx, c in enumerate(concepts):
        name = c['name'].strip()
        # 跳过重复名称（只保留第一个出现的）
        if name in node_id_map:
            continue

        stats = wrong_stats.get(name, {'wrong': 0, 'total': 0})
        definition = c['definition'] or ''
        domain = classify_domain(name, definition)

        node = {
            'id': c['id'],
            'name': name,
            'definition': definition,
            'type': c['type_name'],
            'domain': domain,
            'wrong_count': stats['wrong'],
            'total_count': stats['total'],
        }
        node_id_map[name] = idx
        nodes.append(node)

    # 重新建立 id->name 映射（只保留唯一的）
    unique_names = set()
    for c in concepts:
        name = c['name'].strip()
        if name not in unique_names:
            unique_names.add(name)

    # 构建 edges
    edges = []
    seen_edges = set()
    for src_name, tgt_name, rel_type in EDGE_DEFINITIONS:
        # 检查两个概念名是否都存在
        if src_name not in node_id_map or tgt_name not in node_id_map:
            continue
        edge_key = f'{src_name}|{tgt_name}|{rel_type}'
        if edge_key in seen_edges:
            continue
        seen_edges.add(edge_key)
        edges.append({
            'source': src_name,
            'target': tgt_name,
            'relation': rel_type,
        })

    return {'nodes': nodes, 'edges': edges}


def main():
    graph = build_graph()
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
        json.dump(graph, f, ensure_ascii=False, indent=2)

    print(f'✅ 知识图谱数据已生成: {OUTPUT_PATH}')
    print(f'   节点: {len(graph["nodes"])} 个')
    print(f'   关系: {len(graph["edges"])} 条')

    # 按域名统计
    domains = defaultdict(int)
    types = defaultdict(int)
    for n in graph['nodes']:
        domains[n['domain']] += 1
        types[n['type']] += 1
    print(f'\n   领域分布:')
    for d, c in sorted(domains.items(), key=lambda x: -x[1]):
        print(f'     {d}: {c}个')
    print(f'\n   类型分布:')
    for t, c in sorted(types.items(), key=lambda x: -x[1]):
        print(f'     {t}: {c}个')

    # 关系类型统计
    rel_types = defaultdict(int)
    for e in graph['edges']:
        rel_types[e['relation']] += 1
    print(f'\n   关系类型:')
    for r, c in sorted(rel_types.items(), key=lambda x: -x[1]):
        print(f'     {r}: {c}条')


